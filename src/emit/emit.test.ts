import { describe, expect, test } from 'bun:test';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { contractFor } from '../contracts/registry.js';
import { nextIdLedger } from '../registry/ids.js';
import type { Rule } from '../types.js';
import { applyEmit, checkEmit, planEmit } from './index.js';
import { sortDeep } from './merge.js';

function layerRule(id: string, name: string, mayImport: string[], extra = {}): Rule {
  return {
    id,
    kind: 'layers',
    statement: `${name} imports only what it declares`,
    severity: 'error',
    confidence: 'deterministic',
    params: { name, match: `modules/*/${name}/**`, mayImport, ...extra },
    remedy: { summary: 'declare it, or invert the call' },
  };
}

const RULES: Rule[] = [
  layerRule('services-orchestrate-only', 'services', ['domain', 'rules']),
  layerRule('domain-no-service-import', 'domain', ['rules'], { catchesUnlayered: true }),
  layerRule('rules-are-pure', 'rules', []),
  { ...layerRule('switched-off', 'nothing', []), severity: 'off' },
];

function inTempRepo<T>(body: (root: string) => T): T {
  const root = mkdtempSync(join(tmpdir(), 'archcheck-emit-'));
  try {
    return body(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

function plan(root: string, rules: readonly Rule[] = RULES) {
  return planEmit({
    root,
    configPath: join(root, 'architecture.config.ts'),
    rules,
    coverage: { total: rules.length, deterministic: rules.length, proxy: 0, model: 0 },
    contractFor,
  });
}

describe('sortDeep', () => {
  test('sorts keys at every depth so output cannot depend on insertion order', () => {
    const a = JSON.stringify(sortDeep({ z: { b: 1, a: 2 }, y: [{ d: 1, c: 2 }] }));
    const b = JSON.stringify(sortDeep({ y: [{ c: 2, d: 1 }], z: { a: 2, b: 1 } }));
    expect(a).toBe(b);
  });
});

describe('planning', () => {
  test('writes one file per sink, and only for sinks that had fragments', () => {
    inTempRepo((root) => {
      const files = plan(root).files;
      expect(files.map((f) => f.path)).toEqual([
        'graph.config.cjs',
        'lint.overrides.json',
        'rules.json',
      ]);
    });
  });

  test('a rule switched off contributes nothing', () => {
    inTempRepo((root) => {
      const graph = plan(root).files.find((f) => f.target === 'graph');
      expect(graph?.ruleIds).not.toContain('switched-off');
      expect(graph?.content).not.toContain('switched-off');
    });
  });
});

describe('the generated header', () => {
  test('the .cjs sink opens with a comment header naming source, rules and the command', () => {
    inTempRepo((root) => {
      const graph = plan(root).files.find((f) => f.target === 'graph');
      const lines = (graph?.content ?? '').split('\n');
      expect(lines[0]).toBe('// GENERATED BY archcheck — DO NOT EDIT');
      expect(lines[1]).toBe('// source: architecture.config.ts');
      expect(lines[2]).toBe(
        '// rules:  domain-no-service-import, rules-are-pure, services-orchestrate-only',
      );
      expect(lines[3]).toBe('// regenerate: npx archcheck emit');
    });
  });

  test('the JSON sink carries the same four facts under $generated, since // is not JSON', () => {
    inTempRepo((root) => {
      const lint = plan(root).files.find((f) => f.target === 'lint');
      const parsed = JSON.parse(lint?.content ?? '{}');
      expect(parsed.$generated).toEqual({
        by: 'archcheck',
        doNotEdit: true,
        regenerate: 'npx archcheck emit',
        rules: ['domain-no-service-import', 'rules-are-pure'],
        source: 'architecture.config.ts',
      });
    });
  });
});

describe('the statement goes into the lint message', () => {
  test('so the editor shows the architecture’s own sentence, not a rule name', () => {
    inTempRepo((root) => {
      const lint = plan(root).files.find((f) => f.target === 'lint');
      const parsed = JSON.parse(lint?.content ?? '{}');
      const entry = parsed.rules.find(
        (r: { ruleId: string }) => r.ruleId === 'domain-no-service-import',
      );
      expect(entry.message).toBe(
        'domain imports only what it declares — declare it, or invert the call',
      );
      expect(entry.files).toEqual(['modules/*/domain/**']);
      expect(entry.forbiddenLayers).toEqual(['services']);
    });
  });
});

describe('determinism', () => {
  test('re-emitting an unchanged manifest is byte-identical', () => {
    inTempRepo((root) => {
      const first = plan(root).files.map((f) => f.content);
      // Rules given in a different order must produce the same bytes.
      const shuffled = [...RULES].reverse();
      const second = plan(root, shuffled).files.map((f) => f.content);
      expect(second).toEqual(first);
    });
  });

  test('a second write reports nothing changed', () => {
    inTempRepo((root) => {
      const ledger = nextIdLedger({ schemaVersion: 1, ids: [] }, RULES);
      const firstWrite = applyEmit(plan(root), ledger);
      expect(firstWrite.written.every((w) => w.changed)).toBe(true);
      const secondWrite = applyEmit(plan(root), ledger);
      expect(secondWrite.written.every((w) => w.changed)).toBe(false);
    });
  });
});

describe('emit --check', () => {
  test('reports every sink as missing before the first emit', () => {
    inTempRepo((root) => {
      const stale = checkEmit(plan(root));
      expect(stale.map((s) => s.reason)).toEqual(['missing', 'missing', 'missing']);
    });
  });

  test('is clean immediately after an emit', () => {
    inTempRepo((root) => {
      applyEmit(plan(root), nextIdLedger({ schemaVersion: 1, ids: [] }, RULES));
      expect(checkEmit(plan(root))).toEqual([]);
    });
  });

  test('catches a hand-edited generated file, and names it', () => {
    inTempRepo((root) => {
      applyEmit(plan(root), nextIdLedger({ schemaVersion: 1, ids: [] }, RULES));
      const victim = join(root, 'generated', 'graph.config.cjs');
      writeFileSync(victim, `${readFileSync(victim, 'utf8')}\n// someone typed here\n`);

      const stale = checkEmit(plan(root));
      expect(stale).toHaveLength(1);
      expect(stale[0]?.path).toBe('generated/graph.config.cjs');
      expect(stale[0]?.reason).toBe('hand-edited');
    });
  });

  test('catches a manifest change that was never re-emitted', () => {
    inTempRepo((root) => {
      applyEmit(plan(root), nextIdLedger({ schemaVersion: 1, ids: [] }, RULES));
      const widened = RULES.map((r) =>
        r.id === 'rules-are-pure' ? { ...r, statement: 'rules are pure, truly' } : r,
      );
      const stale = checkEmit(plan(root, widened));
      expect(stale.length).toBeGreaterThan(0);
    });
  });
});

describe('the id ledger', () => {
  test('is written by emit, so ids become immutable as a reviewed diff', () => {
    inTempRepo((root) => {
      const ledger = nextIdLedger({ schemaVersion: 1, ids: ['an-older-id'] }, RULES);
      applyEmit(plan(root), ledger);
      const written = JSON.parse(readFileSync(join(root, '.archcheck', 'ids.json'), 'utf8'));
      expect(written.ids).toEqual([
        'an-older-id',
        'domain-no-service-import',
        'rules-are-pure',
        'services-orchestrate-only',
        'switched-off',
      ]);
    });
  });
});

describe('an unimplemented kind', () => {
  test('is reported rather than silently emitting nothing', () => {
    inTempRepo((root) => {
      // Every kind in the closed set of eight now has a contract type except `forbidden`, which
      // is a one-edge special case `layers` already covers.
      const withUnimplemented: Rule[] = [
        ...RULES,
        {
          id: 'one-specific-edge',
          kind: 'forbidden',
          statement: 'this one edge is banned',
          severity: 'error',
          confidence: 'deterministic',
          params: { from: 'a/**', to: 'b/**' },
          remedy: { summary: 'do not import it' },
        },
      ];
      expect(plan(root, withUnimplemented).unimplemented).toEqual(['forbidden']);
    });
  });
});
